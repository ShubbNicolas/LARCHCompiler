package compiler.parser;

import java.util.List;

/**
 * LARCH（LSL 子集）抽象语法树。
 *
 * <p>覆盖不断扩展的真实样例，例如：</p>
 * <pre>
 * Container(E, C): trait
 *   includes InsertGenerated, Integer
 *   asserts
 *     C partitioned by isEmpty, head, tail
 *   converts isEmpty, count
 *   exempting head(empty)
 *
 * PQueue(E, Q): trait
 *   includes Container(Q for C)
 *   implies  q: Q, e: E
 *     e ∈ q ⇒ (e ≤ head(q))
 * </pre>
 */
public final class Ast {

    private Ast() {
    }

    /**
     * 一个完整的 trait 规格。
     *
     * @param name       trait 名
     * @param parameters 形参，可为空
     * @param sections   introduces / asserts / includes / assumes / implies / converts / exempting
     * @param implied    {@code implies TotalOrder(Str)} 这种引用式 implies
     */
    public record Trait(String name, List<String> parameters,
                        List<Section> sections, List<Ref> implied) {
    }

    /** 重命名实例化中的一对映射，如 {@code Q for C}。 */
    public record Rename(String from, String to) {
        public String display() {
            return from + " for " + to;
        }
    }

    /**
     * 名称引用：{@code TotalOrder(E)}、{@code DerivedOrders(Str)}、{@code Container(Q for C)}。
     *
     * @param name      名称
     * @param arguments 位置实参（{@code Trait(Sort1, Sort2)} 形式）
     * @param renames   重命名映射（{@code Trait(A for B)} 形式）
     */
    public record Ref(String name, List<String> arguments, List<Rename> renames) {

        public String display() {
            if (!renames.isEmpty()) {
                return name + "(" + String.join(", ",
                        renames.stream().map(Rename::display).toList()) + ")";
            }
            if (!arguments.isEmpty()) {
                return name + "(" + String.join(", ", arguments) + ")";
            }
            return name;
        }
    }

    public sealed interface Section
            permits Introduces, Asserts, Includes, Assumes, Implies, Converts, Exempting {
    }

    /** {@code introduces} 段：算子签名列表。 */
    public record Introduces(List<Signature> signatures) implements Section {
    }

    /** {@code includes} 段：被包含的其它 trait。 */
    public record Includes(List<Ref> traits) implements Section {
    }

    /** {@code assumes} 段：本 trait 依赖的前置规格。 */
    public record Assumes(List<Ref> assumptions) implements Section {
    }

    /** {@code implies} 公式块：量化变量 + 需要被包含者满足的等式。 */
    public record Implies(List<VarDecl> variables, List<Equation> equations) implements Section {
    }

    /** {@code converts} 子句：本 trait 唯一确定其取值的算子。 */
    public record Converts(List<Ref> operators) implements Section {
    }

    /** {@code exempting} 子句：豁免某些无定义情形。 */
    public record Exempting(List<Ref> cases) implements Section {
    }

    /**
     * {@code asserts} 段。
     *
     * @param generatedBy      {@code Str generated by empty, -|} 中的算子
     * @param partitionedSort  {@code C partitioned by ...} 中的排序，可为空
     * @param partitionedBy    划分算子
     * @param variables        变量声明
     * @param equations        等式
     */
    public record Asserts(List<Ref> generatedBy, String partitionedSort,
                          List<Ref> partitionedBy, List<VarDecl> variables,
                          List<Equation> equations) implements Section {
    }

    /** 算子签名，例如 {@code add: Tab, Ind, Val → Tab}。 */
    public record Signature(String name, List<String> argumentSorts, String resultSort) {
    }

    /** 变量声明，例如 {@code i, i1: Ind}。 */
    public record VarDecl(List<String> names, String sort) {
    }

    /** 等式，例如 {@code size(new) == 0}。 */
    public record Equation(Expr left, Expr right) {
    }

    public sealed interface Expr permits Num, Text, Name, Apply, Infix, Negate, Conditional {
    }

    public record Num(int value) implements Expr {
    }

    public record Text(String value) implements Expr {
    }

    public record Name(String id) implements Expr {
    }

    public record Apply(String function, List<Expr> arguments) implements Expr {
    }

    public record Infix(String operator, Expr left, Expr right) implements Expr {
    }

    public record Negate(Expr operand) implements Expr {
    }

    public record Conditional(Expr condition, Expr whenTrue, Expr whenFalse) implements Expr {
    }
}
