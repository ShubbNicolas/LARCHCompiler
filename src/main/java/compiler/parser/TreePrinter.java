package compiler.parser;

import java.util.List;
import java.util.stream.Collectors;

/**
 * 把 AST 渲染成缩进文本，用于界面右侧「语法分析」结果区。
 */
public final class TreePrinter {

    private TreePrinter() {
    }

    public static String render(Ast.Trait trait) {
        if (trait == null) {
            return "(无语法树)";
        }
        StringBuilder sb = new StringBuilder();
        sb.append("Trait ").append(trait.name());
        if (!trait.parameters().isEmpty()) {
            sb.append('(').append(String.join(", ", trait.parameters())).append(')');
        }
        sb.append('\n');

        int total = trait.sections().size() + (trait.implied().isEmpty() ? 0 : 1);
        int index = 0;
        for (Ast.Section section : trait.sections()) {
            index++;
            renderSection(sb, section, "", index == total);
        }
        if (!trait.implied().isEmpty()) {
            sb.append("└─ implies ").append(joinRefs(trait.implied())).append('\n');
        }
        return sb.toString();
    }

    private static void renderSection(StringBuilder sb, Ast.Section section, String indent, boolean last) {
        String branch = last ? "└─ " : "├─ ";
        String childIndent = indent + (last ? "   " : "│  ");

        if (section instanceof Ast.Introduces intro) {
            sb.append(indent).append(branch).append("introduces\n");
            for (int i = 0; i < intro.signatures().size(); i++) {
                Ast.Signature sig = intro.signatures().get(i);
                boolean sigLast = i == intro.signatures().size() - 1;
                sb.append(childIndent).append(sigLast ? "└─ " : "├─ ")
                        .append(sig.name()).append(" : ");
                if (!sig.argumentSorts().isEmpty()) {
                    sb.append(String.join(", ", sig.argumentSorts())).append(" → ");
                } else {
                    sb.append("→ ");
                }
                sb.append(sig.resultSort()).append('\n');
            }
            return;
        }

        if (section instanceof Ast.Asserts asserts) {
            sb.append(indent).append(branch).append("asserts\n");
            if (!asserts.generatedBy().isEmpty()) {
                sb.append(childIndent).append("├─ generated by ")
                        .append(joinRefs(asserts.generatedBy())).append('\n');
            }
            if (asserts.partitionedSort() != null) {
                sb.append(childIndent).append("├─ ").append(asserts.partitionedSort())
                        .append(" partitioned by ").append(joinRefs(asserts.partitionedBy()))
                        .append('\n');
            }
            if (!asserts.variables().isEmpty()) {
                sb.append(childIndent).append("├─ vars: ").append(joinVarDecls(asserts.variables()))
                        .append('\n');
            }
            renderEquations(sb, childIndent, asserts.equations());
            return;
        }

        if (section instanceof Ast.Implies implies) {
            sb.append(indent).append(branch).append("implies\n");
            if (!implies.variables().isEmpty()) {
                sb.append(childIndent).append("├─ vars: ").append(joinVarDecls(implies.variables()))
                        .append('\n');
            }
            renderEquations(sb, childIndent, implies.equations());
            return;
        }

        if (section instanceof Ast.Includes includes) {
            sb.append(indent).append(branch).append("includes ")
                    .append(joinRefs(includes.traits())).append('\n');
            return;
        }

        if (section instanceof Ast.Assumes assumes) {
            sb.append(indent).append(branch).append("assumes ")
                    .append(joinRefs(assumes.assumptions())).append('\n');
            return;
        }

        if (section instanceof Ast.Converts converts) {
            sb.append(indent).append(branch).append("converts ")
                    .append(joinRefs(converts.operators())).append('\n');
            return;
        }

        if (section instanceof Ast.Exempting exempting) {
            sb.append(indent).append(branch).append("exempting ")
                    .append(joinRefs(exempting.cases())).append('\n');
            return;
        }

        sb.append(indent).append(branch).append(section).append('\n');
    }

    private static void renderEquations(StringBuilder sb, String indent, List<Ast.Equation> equations) {
        for (int i = 0; i < equations.size(); i++) {
            Ast.Equation eq = equations.get(i);
            boolean eqLast = i == equations.size() - 1;
            sb.append(indent).append(eqLast ? "└─ " : "├─ ")
                    .append(expr(eq.left())).append(" == ").append(expr(eq.right()))
                    .append('\n');
        }
    }

    private static String joinVarDecls(List<Ast.VarDecl> variables) {
        return variables.stream()
                .map(d -> String.join(", ", d.names()) + ": " + d.sort())
                .collect(Collectors.joining("; "));
    }

    private static String joinRefs(List<Ast.Ref> refs) {
        return refs.stream().map(Ast.Ref::display).collect(Collectors.joining(", "));
    }

    public static String expr(Ast.Expr expression) {
        if (expression instanceof Ast.Num n) {
            return String.valueOf(n.value());
        }
        if (expression instanceof Ast.Text t) {
            return '"' + t.value() + '"';
        }
        if (expression instanceof Ast.Name n) {
            return n.id();
        }
        if (expression instanceof Ast.Apply a) {
            return a.function() + "(" + String.join(", ", a.arguments().stream()
                    .map(TreePrinter::expr).toList()) + ")";
        }
        if (expression instanceof Ast.Infix i) {
            return "(" + expr(i.left()) + " " + i.operator() + " " + expr(i.right()) + ")";
        }
        if (expression instanceof Ast.Negate n) {
            return "~" + expr(n.operand());
        }
        if (expression instanceof Ast.Conditional c) {
            return "if " + expr(c.condition()) + " then " + expr(c.whenTrue())
                    + " else " + expr(c.whenFalse());
        }
        return String.valueOf(expression);
    }
}
