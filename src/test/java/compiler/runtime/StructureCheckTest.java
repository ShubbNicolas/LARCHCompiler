package compiler.runtime;

import compiler.parser.Ast;
import compiler.parser.ParseResult;
import compiler.parser.Parser;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/**
 * 结构检查：introduces 声明的算子是否都被 asserts 定义。
 */
class StructureCheckTest {

    private static Ast.Trait trait(String source) {
        ParseResult parsed = Parser.parse(source);
        assertFalse(parsed.hasErrors(), () -> "语法错误: " + parsed.errors());
        return parsed.trait();
    }

    @Test
    @DisplayName("Container：声明的算子都有定义，无警告")
    void containerHasNoFindings() {
        Ast.Trait t = trait("""
                Container(E, C): trait
                  introduces
                    isEmpty: C → Bool
                    count: E, C → Int
                    __ ∈ __: E, C → Bool
                    head: C → E
                    tail: C → C
                  asserts
                    C partitioned by isEmpty, head, tail
                    e: E, c: C
                    isEmpty(empty);
                    count(e, empty) == 0;
                    (e ∈ c) == count(e, c) > 0
                """);
        assertTrue(StructureCheck.check(t).isEmpty(),
                () -> String.valueOf(StructureCheck.check(t)));
    }

    @Test
    @DisplayName("声明了却没有任何等式定义 → 报告警告")
    void declaredButUndefined() {
        Ast.Trait t = trait("""
                T: trait
                introduces
                  size: C → Int
                  mystery: C → Int
                asserts c: C
                  size(c) == 0
                """);
        List<StructureCheck.Finding> findings = StructureCheck.check(t);
        assertEquals(1, findings.size(), () -> String.valueOf(findings));
        assertTrue(findings.get(0).message().contains("mystery"));
    }

    @Test
    @DisplayName("converts 中列出的算子视为已定义")
    void convertsCounts() {
        Ast.Trait t = trait("""
                T: trait
                introduces
                  empty: → C
                  size: C → Int
                asserts c: C
                  size(c) == 0
                converts empty
                """);
        assertTrue(StructureCheck.check(t).isEmpty(),
                () -> String.valueOf(StructureCheck.check(t)));
    }

    @Test
    @DisplayName("generated by 中列出的算子视为已定义")
    void generatedByCounts() {
        Ast.Trait t = trait("""
                T: trait
                introduces
                  empty: → C
                  insert: C → C
                asserts
                  C generated by empty, insert
                  c: C
                  insert(c) == c
                """);
        assertTrue(StructureCheck.check(t).isEmpty(),
                () -> String.valueOf(StructureCheck.check(t)));
    }

    @Test
    @DisplayName("算子形参不参与检查（由实例化方提供定义）")
    void operatorParameterSkipped() {
        Ast.Trait t = trait("""
                P(⊕, E): trait
                introduces
                  __ ⊕ __: E, E → E
                asserts e1, e2: E
                  e1 == e1
                """);
        assertTrue(StructureCheck.check(t).isEmpty(),
                () -> String.valueOf(StructureCheck.check(t)));
    }

    @Test
    @DisplayName("字面量签名（0,1）不参与检查")
    void literalSignatureSkipped() {
        Ast.Trait t = trait("""
                T: trait
                introduces
                  0, 1: → Int
                  size: C → Int
                asserts c: C
                  size(c) == 0
                """);
        assertTrue(StructureCheck.check(t).isEmpty(),
                () -> String.valueOf(StructureCheck.check(t)));
    }

    @Test
    @DisplayName("Table1 样例存在声明未定义的结构警告")
    void table1HasFindings() {
        Ast.Trait t = trait("""
                Table1: trait
                introduces
                  new: → Tab
                  add: Tab, Ind, Val → Tab
                  __ ∈ __: Ind, Tab → Bool
                  lookup: Tab, Ind → Val
                  isEmpty: Tab → Bool
                  size: Tab → Int
                asserts i, i1: Ind, val: Val, t: Tab
                  lookup(add(t, i, val), i1) ==
                    if i = i1 then val else lookup(t, i1);
                  size(new) == 0;
                  isEmpty(t) == size(t) = 0
                """);
        List<StructureCheck.Finding> findings = StructureCheck.check(t);
        assertEquals(3, findings.size(), () -> String.valueOf(findings));
        assertTrue(findings.stream().anyMatch(f -> f.message().contains("new")));
        assertTrue(findings.stream().anyMatch(f -> f.message().contains("__ ∈ __")));
    }
}
